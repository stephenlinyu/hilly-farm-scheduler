def build_field_polygon(lng, lat, area_sqm, index):
    """按记录面积生成旋转矩形，返回前端使用的 [lat, lng] 坐标。"""
    aspect_ratio = (1.25, 1.45, 1.65, 1.85)[index % 4]
    width_m = math.sqrt(area_sqm * aspect_ratio)
    height_m = area_sqm / width_m
    angle = math.radians(((index * 17) % 50) - 25)
    meters_per_lng = 111_320.0 * math.cos(math.radians(lat))
    meters_per_lat = 111_320.0
    corners = []
    for x, y in (
        (-width_m / 2, -height_m / 2),
        (width_m / 2, -height_m / 2),
        (width_m / 2, height_m / 2),
        (-width_m / 2, height_m / 2),
    ):
        rotated_x = x * math.cos(angle) - y * math.sin(angle)
        rotated_y = x * math.sin(angle) + y * math.cos(angle)
        corners.append([
            round(lat + rotated_y / meters_per_lat, 7),
            round(lng + rotated_x / meters_per_lng, 7),
        ])
    return json.dumps(corners, ensure_ascii=False)


